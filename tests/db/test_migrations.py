"""Migrations match the models and run in both directions on a clean database."""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import ROOT


def _config(url: str) -> Config:
    config = Config(str(ROOT / "alembic.ini"))
    config.attributes["database_url"] = url
    config.attributes["configure_logger"] = False
    return config


def test_models_and_migrations_agree(migrated: str) -> None:
    with ThreadPoolExecutor(max_workers=1) as pool:
        future = pool.submit(command.check, _config(migrated))
        try:
            future.result()
        except AutogenerateDiffsDetected as error:  # pragma: no cover - the failure message is the diff
            raise AssertionError(str(error)) from error


def test_downgrade_and_upgrade_again(migrated: str) -> None:
    config = _config(migrated)
    with ThreadPoolExecutor(max_workers=1) as pool:
        pool.submit(command.downgrade, config, "base").result()
        pool.submit(command.upgrade, config, "head").result()
